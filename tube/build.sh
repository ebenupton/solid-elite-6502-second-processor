#!/bin/sh
# Build the 6502 Second Processor (Tube) version of the full Master port
# (docs/TUBE-PLAN.md, docs/TUBE-MAP.md) into tube/build:
#   build/PCODE.bin    the parasite's image: the game, the frame layer and the
#                      Tube glue, one flat run from CODE%
#   build/H*.bin       the host's images (main RAM and sideways RAM banks)
#   build/psyms.txt, build/hsyms.txt   the two assemblies' symbols
#   build/elite-tube.ssd   the disc (SHIFT+BREAK on a host with a 6502 Second
#                      Processor)
#
# The game's source is master/src's, assembled with _TUBE (and the renderer's
# files with _TPART = 1 for the parasite's part, 2 for the host's). The stage
# directory makes master/src look like the Tube's build: src/ is master/src,
# build/ is tube/build, tsrc/ is tube/src, tools/ is master/tools, so the
# game's own INCLUDEs ("build/...", "src/...") resolve here.
set -e
cd "$(dirname "$0")"
TUBE_DIR=$(pwd)
BEEBASM=${BEEBASM:-$TUBE_DIR/../tools/beebasm}
mkdir -p build stage
ln -sfn ../../master/src stage/src
ln -sfn ../build stage/build
ln -sfn ../src stage/tsrc
ln -sfn ../../master/tools stage/tools
cd stage
rm -f build/*.bin build/*.ssd
cat > build/elite-build-options.asm <<EOF
_VERSION=4
_VARIANT=1
_REMOVE_CHECKSUMS=TRUE
_MATCH_ORIGINAL_BINARIES=TRUE
_MAX_COMMANDER=FALSE
_TUBE=TRUE
_TDUMB=TRUE
EOF
: > build/compile.txt
python3 tools/dashboard.py build > /dev/null
python3 - <<'PY'                     # the glyphs' W nibbles for the parasite's H_CHAR (p-glue.asm)
f = open("src/fonts/P.FONT.bin", "rb").read()
open("build/fontw.asm", "w").write(" EQUB " + ", ".join("&%02X" % (f[8 * i] & 15) for i in range(96)) + "\n")
PY
TUBE=1 python3 tools/streams.py >> build/compile.txt || { tail -20 build/compile.txt; exit 1; }
$BEEBASM -i build/elite-data-bdata.asm -v >> build/compile.txt 2>&1 || { tail -20 build/compile.txt; exit 1; }
# the parasite
$BEEBASM -D OPTEST=${OPTEST:-0} -D MEASURE=${MEASURE:-0} -i tsrc/p-layout.asm -v > build/compile-p.txt 2>&1 || { grep -iE "error" -A3 build/compile-p.txt | head -30; exit 1; }
$BEEBASM -D OPTEST=${OPTEST:-0} -D MEASURE=${MEASURE:-0} -i tsrc/p-layout.asm -d > build/psyms.txt 2>/dev/null
# the overlays' sizes, for the hosts' storage of their images (p-ovl.asm)
python3 - <<'PY'
import re
sy = {}
for m in re.finditer(r"'([^']+)':(\d+)", open("build/psyms.txt").read()):
    sy.setdefault(m.group(1), int(m.group(2)))
with open("build/povl.asm", "w") as f:
    f.write("\\ Generated by tube/build.sh: the parasite's overlays (p-ovl.asm)\n")
    f.write("OVLD_PAGES = %d\n" % ((sy["OVL_D_END"] + 255) // 256 - sy["OVL_START"] // 256))
    f.write("OVLS_PAGES = %d\n" % ((sy["OVL_S_END"] + 255) // 256 - sy["OVL_START"] // 256))
    f.write("OVLSS_PAGES = %d\n" % ((sy["S_STATE_END"] + 255) // 256 - sy["OVL_START"] // 256))
    f.write("OVLSC_PAGES = %d\n" % (sy["TAIL_START"] // 256 - sy["OVL_START"] // 256))   # (S's common part, from OVL_START)
    f.write("OVLS0_PAGES = %d\n" % (sy["S_STATE_END"] // 256 - sy["OVL_START"] // 256))   # (the pages of S's image not sent: the state's, p-ovl.asm's ovl_sinit)
    f.write("OVLTC_PAGES = %d\n" % ((sy["TC_END"] + 255) // 256 - sy["TAIL_START"] // 256))
# overlay S's crater tail goes after overlay D's image (the hosts keep both in one bank)
d = open("build/HOVD.bin", "rb").read(); c = open("build/HOVSC.bin", "rb").read()
assert len(d) % 256 == 0 and len(c) % 256 == 0
open("build/HOVD.bin", "wb").write(d + c)
# S's image as ovl_sinit makes its state: zeros but for r_dyt, r_dst (2 each) and r_wt
img = open("build/HOVS.bin", "rb").read()
st = bytearray(sy["S_STATE_END"] - sy["OVL_START"])
for n, k in (("r_dyt", 2), ("r_dst", 2), ("r_wt", 1)):
    for i in range(k): st[sy[n] - sy["OVL_START"] + i] = 0xFF
assert img[:len(st)] == bytes(st), "S's state in its image is not what ovl_sinit makes"
# the Master host's storage of the overlays (h-main.asm's h_ovlget): page by
# page, in the regions the STA runs and the code leave (build/hstore.asm: each
# page's ROMSEL and address; tube/build.sh's hstore step fills the images)
pg = lambda a: a // 256
o = pg(sy["OVL_START"])
ovs = [  # (name, number, first page sent, pages)
    ("D", 1, o, pg(sy["OVL_D_END"] + 255) - o),
    ("TC", 5, pg(sy["TAIL_START"]), pg(sy["TC_END"] + 255) - pg(sy["TAIL_START"])),
    ("S", 2, pg(sy["S_STATE_END"]), pg(sy["TAIL_START"]) - pg(sy["S_STATE_END"])),
    ("TM", 4, pg(sy["TAIL_START"]), pg(sy["OVL_S_END"] + 255) - pg(sy["TAIL_START"]))]
nss = pg(sy["S_STATE_END"] + 255) - o   # (S's state: in 64-byte pieces, bytes 192-255 of
assert 4 * nss <= 64                    # bank 4's run pages, h-main.asm's hss)
REG = [  # (ROMSEL, first page, pages): main RAM (ACCCON X clear), bank 5's
    (6, 0x30, 14), (6, 0x70, 16),       # tail, bank 6's tail (after its STA
    (5, 0xBB, 5), (6, 0xB7, 9),         # runs), ANDY's tail, HAZEL above the
    (0x85, 0x86, 10), (6, 0xCA, 22)]    # code that enters the runs
slots = [(r, h + i) for r, h, n in REG for i in range(n)]
total = sum(n for _, _, n, in [(0, 0, x[3]) for x in ovs])
assert total <= len(slots), "the overlays need %d pages, the regions hold %d" % (total, len(slots))
first, k = {}, 0
for name, num, p0, n in ovs:
    first[num] = (k, n); k += n
with open("build/hstore.asm", "w") as f:
    f.write("\\ Generated by tube/build.sh: the Master host's storage of the overlays\n")
    f.write("HST_PAGES = %d\n" % total)
    f.write(".st_rom EQUB %s\n" % ", ".join("&%02X" % slots[i][0] for i in range(total)))
    f.write(".st_hi EQUB %s\n" % ", ".join("&%02X" % slots[i][1] for i in range(total)))
    first[3] = (0, nss)
    f.write(".h_ovf EQUB %s\n" % ", ".join(str(first[n][0]) for n in range(1, 6)))
    f.write(".h_ovn EQUB %s\n" % ", ".join(str(first[n][1]) for n in range(1, 6)))
# the pages' contents, by slot (build/hstore.bin: ROMSEL, page, 256 bytes each)
hovd = open("build/HOVD.bin", "rb").read()
srcs = {"D": hovd[:256 * ovs[0][3]], "TC": hovd[256 * ovs[0][3]:],
        "S": img[256 * (pg(sy["S_STATE_END"]) - o):256 * (pg(sy["TAIL_START"]) - o)],
        "TM": img[256 * (pg(sy["TAIL_START"]) - o):]}
out = bytearray()
k = 0
for name, num, p0, n in ovs:
    data = srcs[name]
    assert len(data) == 256 * n, (name, len(data), n)
    for i in range(n):
        r, h = slots[k]; k += 1
        out += bytes([r, h]) + data[256 * i:256 * i + 256]
open("build/hstore.bin", "wb").write(out)
PY
# the host
$BEEBASM -i tsrc/h-layout.asm -v > build/compile-h.txt 2>&1 || { grep -iE "error" -A3 build/compile-h.txt | head -30; exit 1; }
$BEEBASM -i tsrc/h-layout.asm -d > build/hsyms.txt 2>/dev/null
