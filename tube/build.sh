import re
h, p = {}, {}
for m in re.finditer(r"'([^']+)':(\d+)", open("build/hsyms.txt").read()):
    h.setdefault(m.group(1), int(m.group(2)))
for m in re.finditer(r"'([^']+)':(\d+)", open("build/psyms.txt").read()):
    p.setdefault(m.group(1), int(m.group(2)))
h["HSTS0"] = int(re.search(r"^HSTS0 = &([0-9A-F]+)", open("tsrc/h-layout.asm").read(), re.M).group(1), 16)
pg = lambda a: a // 256
o = pg(p["OVL_START"])
nd = pg(p["OVL_D_END"] + 255) - o
d = open("build/HOVD.bin", "rb").read()
s = open("build/HOVS.bin", "rb").read()[256 * (pg(p["S_STATE_END"]) - o):]
s += bytes(-len(s) % 256)
assert len(d) == 256 * nd
open("build/HOVSK.bin", "wb").write(s)
dslots = [(0x40 | (4 + q // 16), 0x80 + 4 * (q % 16)) for q in range(nd)]
