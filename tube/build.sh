#!/bin/sh
# Build the 6502 Second Processor (Tube) version of the full Master port
# (docs/TUBE-PLAN.md, docs/TUBE-MAP.md) into tube/build:
#   build/PCODE.bin    the parasite's image: the game, the frame layer and the
#                      Tube glue, one flat run from CODE%
#   build/H*.bin       the host's images (main RAM and sideways RAM banks)
#   build/psyms.txt, build/hsyms.txt   the two assemblies' symbols
#   build/elite-tube.ssd   the disc (SHIFT+BREAK on a host with a 6502 Second
#                      Processor)
#
# The game's source is master/src's, assembled with _TUBE (and the renderer's
# files with _TPART = 1 for the parasite's part, 2 for the host's). The stage
# directory makes master/src look like the Tube's build: src/ is master/src,
# build/ is tube/build, tsrc/ is tube/src, tools/ is master/tools, so the
# game's own INCLUDEs ("build/...", "src/...") resolve here.
set -e
cd "$(dirname "$0")"
TUBE_DIR=$(pwd)
BEEBASM=${BEEBASM:-$TUBE_DIR/../tools/beebasm}
mkdir -p build stage
ln -sfn ../../master/src stage/src
ln -sfn ../build stage/build
ln -sfn ../src stage/tsrc
ln -sfn ../../master/tools stage/tools
cd stage
rm -f build/*.bin build/*.ssd
cat > build/elite-build-options.asm <<EOF
_VERSION=4
_VARIANT=1
_REMOVE_CHECKSUMS=TRUE
_MATCH_ORIGINAL_BINARIES=TRUE
_MAX_COMMANDER=FALSE
_TUBE=TRUE
EOF
: > build/compile.txt
python3 tools/dashboard.py build > /dev/null
TUBE=1 python3 tools/streams.py >> build/compile.txt || { tail -20 build/compile.txt; exit 1; }
$BEEBASM -i build/elite-data-bdata.asm -v >> build/compile.txt 2>&1 || { tail -20 build/compile.txt; exit 1; }
# the parasite
$BEEBASM -i tsrc/p-layout.asm -v > build/compile-p.txt 2>&1 || { grep -iE "error" -A3 build/compile-p.txt | head -30; exit 1; }
$BEEBASM -i tsrc/p-layout.asm -d > build/psyms.txt 2>/dev/null
# the host
$BEEBASM -i tsrc/h-layout.asm -v > build/compile-h.txt 2>&1 || { grep -iE "error" -A3 build/compile-h.txt | head -30; exit 1; }
$BEEBASM -i tsrc/h-layout.asm -d > build/hsyms.txt 2>/dev/null
# build/hbanks.txt: the host's labels in sideways RAM and the ROMSEL value of
# their bank (5: bank 5, 85: ANDY over bank 5, 6: bank 6), for the profilers
python3 - <<'PY'
import re
with open("build/hbanks.txt", "w") as f:
    for src, bank in (("src/gfx-raster.asm", "5"), ("src/gfx-raster_disc.asm", "5"), ("src/gfx-raster_lcold.asm", "5"),
                      ("src/gfx-flare.asm", "5"), ("src/gfx-raster_poly.asm", "85"), ("src/gfx-raster_line.asm", "85"),
                      ("src/gfx-frame.asm", "6"), ("src/gfx-frame_cold.asm", "6"), ("src/gfx-flare6.asm", "6")):
        for m in re.finditer(r"^\s*\.([A-Za-z_][\w%]*)", open(src, encoding="latin-1").read(), re.M):
            f.write("%s %s\n" % (m.group(1), bank))
PY
# the commander checksum in NA% (as elite-checksum.py)
python3 - <<'PY'
import re
sy = {}
for m in re.finditer(r"'([^']+)':(\d+)", open("build/psyms.txt").read()):
    sy.setdefault(m.group(1), int(m.group(2)))
img = bytearray(open("build/PCODE.bin", "rb").read())
base = int(re.search(r"Parasite: code &&?([0-9A-F]+)", open("build/compile-p.txt").read()).group(1), 16)
cs = sy["NA2%"] - base
CH, CY = 0x4B - 2, 0
for i in range(CH, 0, -1):
    CH = CH + CY + img[cs + i + 7]
    CY = (CH > 255) & 1
    CH = CH % 256
    CH = CH ^ img[cs + i + 8]
img[cs + 0x52] = CH ^ 0xA9
img[cs + 0x52 + 1] = CH
open("build/PCODE.bin", "wb").write(img)
PY
# the loader (the Master port's, tube/src/loader.asm), with the addresses it
# needs from the two assemblies
python3 - <<'PY'
import re
def syms(f):
    sy = {}
    for m in re.finditer(r"'([^']+)':(\d+)", open(f).read()):
        sy.setdefault(m.group(1), int(m.group(2)))
    return sy
p, h = syms("build/psyms.txt"), syms("build/hsyms.txt")
with open("build/tube-addresses.asm", "w") as f:
    f.write("\\ Generated by tube/build.sh\n")
    f.write(" PSTART = &%04X\n PCODEAT = &%04X\n" % (p["p_start"], p["PWS_END"] and 0x1500))
    f.write(" hwrch = &%04X\n HMAINAT = &%04X\n" % (h["hwrch"], h["H_START"]))
    f.write(" B5LEN = &%04X\n B6LEN = &%04X\n RALEN = &%04X\n" % (h["B5_END"] - 0x8000, h["B6_END"] - 0x8000, h["RA_END"] - 0x8000))
    f.write(" GFXBANK = 6\n TUBEID = 4\n")
PY
$BEEBASM -i tsrc/loader.asm -v > build/compile-l.txt 2>&1 || { grep -iE "error" -A3 build/compile-l.txt | head; exit 1; }
$BEEBASM -i tsrc/disc.asm -boot ELITE -do build/elite-tube.ssd -title "E L I T E" >> build/compile.txt 2>&1 || { tail -20 build/compile.txt; exit 1; }
grep -E "^(Parasite|Host)" build/compile-p.txt build/compile-h.txt | sed 's/^build\/compile-.\.txt://'
