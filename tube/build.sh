# the Master host's storage of the overlays (h-main.asm's h_ovlget): D's page
# p is quarters 4p to 4p+3, bytes 192-255 of the pages of lines 4p to 4p+3's
# STA runs (h-sta.asm: page &80 + L MOD 64 of bank 4 + L DIV 64), where the
# loader deals its file (HOVD: build/HOVD.bin); S's pages are three extents
# in address order, main RAM from HSTS0 to &3FFF and &7000-&7FFF, then bank 7
# below the host's code (h-layout.asm), where the loader copies its file
# (HOVS: build/HOVSK.bin, S's image from its state's end). The storage page
# by page into build/hstore.bin, for tube/tools/tstore.mjs (ROMSEL, page,
# 256 bytes each; bit 6 of ROMSEL: four 64-byte pieces from that page on)
