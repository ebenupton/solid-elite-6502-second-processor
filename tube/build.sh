import re
out, pend = {}, []
var = set(re.findall(r"^\.(\w+)\s+SKIP", open("build/hb-wsp.asm").read(), re.M))   # (its variables: no listing lines)
for l in open("build/compile-hb.txt", encoding="latin-1"):
    m = re.match(r"^\.\*?\^?([A-Za-z_][\w%]*)\s*$", l)
    if m:
        if m.group(1) not in var: pend.append(m.group(1))
        continue
    m = re.match(r"^\s+([0-9A-F]{4})\s+[0-9A-F]{2}", l)
    if m:
        a = int(m.group(1), 16)
        if 0xB000 <= a < 0xC000:
            for n in pend: out.setdefault(n, a)
        pend = []
open("build/hbksyms.txt", "w").write("[{" + ",".join("'%s':%dL" % kv for kv in out.items()) + "}]\n")
