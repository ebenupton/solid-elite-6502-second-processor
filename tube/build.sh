# the recursive tokens (QQ18, the blocks tagged "Tube: host" in elite-data.asm:
# build/elite-data-host.asm) as stored, for the hosts (h4body's C_TOKEN), and
# where each token starts (build/htokix.asm); the parasite's TBUF (p-glue.asm)
# must hold the deepest chain of tokens printing tokens
printf ' RE = &23\n ORG &1000\n INCLUDE "build/elite-data-host.asm"\n SAVE "build/HQQ18.bin", &1000, P%%\n' > build/htok-gen.asm
$BEEBASM -i build/htok-gen.asm -v > build/compile-htok.txt 2>&1 || { tail -20 build/compile-htok.txt; exit 1; }
python3 - <<'PY'
import re, functools
q = open("build/HQQ18.bin", "rb").read()
starts, toks, cur = [0], [], []
for i, b in enumerate(q):
    if b == 0:
        toks.append(cur); cur = []; starts.append(i + 1)
    else:
        cur.append(b ^ 0x23)
assert len(toks) == 149 and len(cur) == 3, len(toks)    # (tokens 0-148, then three bytes of the original's noise)
with open("build/htokix.asm", "w") as f:
    f.write("\\ Generated by tube/build.sh: where each recursive token starts in HQQ18\n")
    f.write(".HTOKL EQUB %s\n" % ", ".join("LO(HQQ18+%d)" % o for o in starts[:149]))
    f.write(".HTOKH EQUB %s\n" % ", ".join("HI(HQQ18+%d)" % o for o in starts[:149]))
# TBUF's depth: a token's bytes and null, then the deepest token its characters
# print: tokens (14-31, 96-127, 160-255), control code 0 (csh: token 66) and 5
# (fwl: tokens 105, 35, then 119)
@functools.lru_cache(None)
def mb(n):
    return len(toks[n]) + 1 + max([0] + [tt(c) for c in toks[n]])
def tt(c):
    return mb(66) if c == 0 else max(mb(105), mb(35), mb(119)) if c == 5 else \
        mb(c - 160) if c >= 160 else 0 if c >= 128 else mb(c) if c >= 96 else mb(c + 114) if 14 <= c < 32 else 0
d = max(max(mb(n) for n in range(149)), tt(0), tt(5))
n = int(re.search(r"^TBUFN = (\d+)", open("tsrc/p-glue.asm").read(), re.M).group(1))
assert d <= n, "TBUF (p-glue.asm) needs %d bytes" % d
