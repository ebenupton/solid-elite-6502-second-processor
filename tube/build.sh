python3 - <<'PY'
import re
L = open("src/elite-gfx.asm", encoding="latin-1").read().split("\n")
o = next(i for i, l in enumerate(L) if l.startswith("ORG &0E00"))
e = next(i for i, l in enumerate(L) if l.startswith(".WS_END"))
def lines(ls):
    for l in ls:
        m = re.match(r'^INCLUDE "(src/[^"]+)"', l)
        if m: yield from lines(open(m.group(1), encoding="latin-1").read().split("\n"))
        else: yield l
def named(layout, tag="HWS"):
    want = " ".join(l[len(tag) + 3:] for l in open(layout).read().split("\n") if l.startswith("\\ %s " % tag)).split()
    decl = [l for l in lines(L[o:e]) if re.match(r"^\.(\w+)\s+SKIP\b", l) and re.match(r"^\.(\w+)", l).group(1) in want]
    got = [re.match(r"^\.(\w+)", l).group(1) for l in decl]
    assert sorted(got) == sorted(want), "%s's %s: not in the shared workspace: %s" % (layout, tag, set(want) - set(got))
    return decl
length = lambda decl: " + ".join("(%s)" % re.match(r"^\.\w+\s+SKIP\s+([^\\]+)", l).group(1).strip() for l in decl)
decl = named("tsrc/h-layout.asm")
with open("build/h-wsc.asm", "w", encoding="latin-1") as f:
    f.write("\\ Generated by tube/build.sh: elite-gfx.asm's constants\n")
    f.write("\n".join(l for l in L[:o] if not re.match(r"^(RASTBANK|RASTPOLY|GFXBANK|MERIDBANK|ELITEBANK)\b", l)) + "\n")
    f.write("HWS_LEN = %s\n" % length(decl))
with open("build/h-ws.asm", "w", encoding="latin-1") as f:
    f.write("\\ Generated by tube/build.sh: of elite-gfx.asm's shared workspace what\n")
    f.write("\\ h-layout.asm's HWS lines name (HWS_LEN bytes: build/h-wsc.asm)\n")
    f.write(".HWS_START\n" + "\n".join(decl) + "\n.HWS_END\n")
decl = named("tsrc/hb-layout.asm")
with open("build/hb-wsn.asm", "w", encoding="latin-1") as f:
    f.write("\\ Generated by tube/build.sh: of elite-gfx.asm's shared workspace what\n")
    f.write("\\ hb-layout.asm's HWS lines name (HBWS_LEN bytes: build/hb-wsc.asm)\n")
    f.write("\n".join(decl) + "\n")
with open("build/hb-wsc.asm", "w", encoding="latin-1") as f:
    f.write("\\ Generated by tube/build.sh\nHBWS_LEN = %s\n" % length(decl))
with open("build/hb-wsp.asm", "w", encoding="latin-1") as f:
    f.write("\\ Generated by tube/build.sh: of elite-gfx.asm's shared workspace what\n")
    f.write("\\ hb-kernel.asm's HWSP lines name (the Model B host's span kernel)\n")
    f.write("\n".join(named("tsrc/hb-kernel.asm", "HWSP")) + "\n")
