# the commander checksum in NA% (as elite-checksum.py)
python3 - <<'PY'
import re
sy = {}
for m in re.finditer(r"'([^']+)':(\d+)", open("build/psyms.txt").read()):
    sy.setdefault(m.group(1), int(m.group(2)))
img = bytearray(open("build/PCODE.bin", "rb").read())
img += open("build/PSTAGE.bin", "rb").read()   # (the boot's staging, p-layout.asm)
base = int(re.search(r"Parasite: code &&?([0-9A-F]+)", open("build/compile-p.txt").read()).group(1), 16)
cs = sy["NA2%"] - base
CH, CY = 0x4B - 2, 0
for i in range(CH, 0, -1):
    CH = CH + CY + img[cs + i + 7]
    CY = (CH > 255) & 1
    CH = CH % 256
    CH = CH ^ img[cs + i + 8]
img[cs + 0x52] = CH ^ 0xA9
img[cs + 0x52 + 1] = CH
open("build/PCODE.bin", "wb").write(img)
PY
# the Master host's overlay storage (build/hstore.bin) into the images: bank
# 5's disc window, bank 6's tail, ANDY's tail, and the files the loader copies
# to main RAM (HSTM1 &3000, HSTM2 &7000) and HAZEL (HSTZ, staged at &4000)
python3 - <<'PY'
import re
h = {}
for m in re.finditer(r"'([^']+)':(\d+)", open("build/hsyms.txt").read()):
    h.setdefault(m.group(1), int(m.group(2)))
st = open("build/hstore.bin", "rb").read()
pages = [(st[i], st[i + 1], st[i + 2:i + 258]) for i in range(0, len(st), 258)]
def put(fn, base, size, rom, lim):
    img = bytearray(open(fn, "rb").read()) if fn else bytearray()
    img += bytes(max(0, size - len(img)))
    for r, hi, d in pages:
        if r == rom and lim[0] <= hi < lim[1]:
            o = hi * 256 - base
            assert img[o:o + 256] == bytes(256), (fn, hex(hi))
            img[o:o + 256] = d
    return img
h["RUN6"] = int(re.search(r"^RUN6 = &([0-9A-F]+)", open("tsrc/h-sta.asm").read(), re.M).group(1), 16)
assert h["B5_END"] <= 0xBB00 and h["RA_END"] <= 0x8600 and h["RUN6"] + 24 * 256 <= 0xB700 and h["HZ_END"] <= 0xCA00, "the host's code runs into its storage"
img = put("build/HBANK5.bin", 0x8000, 0x4000, 5, (0xBB, 0xC0)); open("build/HBANK5.bin", "wb").write(img)
img = put("build/HBANK6.bin", 0x8000, 0x4000, 6, (0xB7, 0xC0)); open("build/HBANK6.bin", "wb").write(img)
img = put("build/HRASTA.bin", 0x8000, 0x1000, 0x85, (0x86, 0x90)); open("build/HRASTA.bin", "wb").write(img)
open("build/HSTM1.bin", "wb").write(put(None, 0x3000, 0xE00, 6, (0x30, 0x3E)))
open("build/HSTM2.bin", "wb").write(put(None, 0x7000, 0x1000, 6, (0x70, 0x80)))
img = put(None, 0xC000, 0x2000, 6, (0xC0, 0xE0))
hz = open("build/HHAZ.bin", "rb").read()        # (HAZEL's code, h-layout.asm, below the storage)
assert img[:len(hz)] == bytes(len(hz))
img[:len(hz)] = hz
open("build/HSTZ.bin", "wb").write(img)
PY
