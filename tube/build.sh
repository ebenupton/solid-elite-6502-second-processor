    f.write(" hwrch = &%04X\n HMAINAT = &%04X\n" % (h["hwrch"], h["H_START"]))
    f.write(" B5LEN = &%04X\n B6LEN = &%04X\n RALEN = &%04X\n" % tuple(os.path.getsize("build/%s.bin" % n) for n in ("HBANK5", "HBANK6", "HRASTA")))
    f.write(" DFSST = &%04X\n DFSST2 = &%04X\n" % (h["DFSST"], h["DFSST2"]))
    f.write(" GFXBANK = 6\n TUBEID = 4\n")
