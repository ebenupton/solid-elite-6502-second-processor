\ hb-res2.asm - the Model B host's main RAM code (hb-res.asm): hb_tramp: from bank F into bank D or P and back (A, X, Y through)

.tA EQUB 0
.tback
 STA tA
 PAGE GFXBANK
 LDA tA
 RTS
.T_SETBUF               \ both banks' operands for buffer A
 STA tA
 PAGE RASTBANK
 LDA tA
 JSR D_SETBUF
 PAGE RASTPOLY
 LDA tA
 JSR P_SETBUF
 JMP tback
.T_RESETBUF
 TRAMPOLINE RASTBANK, D_RESETBUF
.T_INIT
 TRAMPOLINE RASTBANK, D_INIT
.T_STARERASE
 TRAMPOLINE RASTPOLY, P_STARERASE
.T_STARPLOT
 TRAMPOLINE RASTPOLY, P_STARPLOT
.T_SPAN
 TRAMPOLINE RASTPOLY, P_SPAN
.T_FLARE
 TRAMPOLINE RASTPOLY, P_FLARE
.T_MARKDIRTY
 TRAMPOLINE RASTPOLY, P_MARKDIRTY
.T_DOT
 TRAMPOLINE RASTPOLY, P_DOT
.T_POLY
 TRAMPOLINE RASTPOLY, P_POLY
.T_LINE
 TRAMPOLINE RASTPOLY, P_LINE
.T_DISCROWS
 TRAMPOLINE RASTBANK, D_DISCROWS
.hb_disc                \ the commands received in bank D or P, then the loop
 PAGE RASTBANK
 JSR D_DISC
 JMP hbloop
.hb_poly
 PAGE RASTPOLY
 JSR P_POLYIN
 JMP hbloop
.hb_line
 PAGE RASTPOLY
 JSR P_LINEIN
.hbloop
 PAGE GFXBANK
 JMP hloop
